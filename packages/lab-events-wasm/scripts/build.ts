/**
 * Build crates/lab-events-wasm and inline it for the browser.
 *
 *   pnpm --filter @lab/events-wasm wasm
 *
 * Needs: rustup target wasm32-unknown-unknown, and wasm-bindgen-cli at the same
 * version as the wasm-bindgen crate in Cargo.lock.
 *
 * The .wasm is inlined as base64 so one artifact works in the browser bundle,
 * vitest and the Node benchmark with no bundler or asset configuration. The
 * viewer imports it lazily, so only that page pays for the download.
 */
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { generatedDir, repoRoot, sourceHash } from "./inputs";

const run = (cmd: string, args: string[]) => execFileSync(cmd, args, { cwd: repoRoot, stdio: "inherit" });

run("cargo", ["build", "--locked", "-p", "lab-events-wasm", "--target", "wasm32-unknown-unknown", "--profile", "wasm"]);
const tmp = mkdtempSync(join(tmpdir(), "lab-events-wasm-"));
try {
  run("wasm-bindgen", [
    "--target", "web",
    "--remove-name-section",
    "--remove-producers-section",
    "--out-dir", tmp,
    join(repoRoot, "target/wasm32-unknown-unknown/wasm/lab_events_wasm.wasm"),
  ]);
  // The default loader does `new URL("lab_events_wasm_bg.wasm", import.meta.url)`.
  // Bundlers resolve that pattern statically and would fail on the missing file;
  // we always pass the bytes, so replace it with an error.
  const glue = readFileSync(join(tmp, "lab_events_wasm.js"), "utf8");
  const defaultUrl = /new URL\('lab_events_wasm_bg\.wasm', import\.meta\.url\)/g;
  if ((glue.match(defaultUrl) ?? []).length !== 1) {
    throw new Error("wasm-bindgen output changed: expected exactly one default .wasm URL to patch");
  }
  writeFileSync(
    join(generatedDir, "bindings.js"),
    `// Generated by scripts/build.ts (wasm-bindgen --target web). Do not edit.\n` +
      glue.replace(defaultUrl, `(() => { throw new Error("@lab/events-wasm: pass the wasm bytes to init"); })()`),
  );
  writeFileSync(
    join(generatedDir, "bindings.d.ts"),
    `// Generated by scripts/build.ts (wasm-bindgen --target web). Do not edit.\n` +
      readFileSync(join(tmp, "lab_events_wasm.d.ts"), "utf8"),
  );
  writeFileSync(
    join(generatedDir, "wasm-base64.d.ts"),
    `// Generated by scripts/build.ts. Do not edit.\ndeclare const wasm: string;\nexport default wasm;\n`,
  );
  const wasm = readFileSync(join(tmp, "lab_events_wasm_bg.wasm"));
  writeFileSync(
    join(generatedDir, "wasm-base64.js"),
    `// Generated by scripts/build.ts from crates/lab-events-wasm. Do not edit.\nexport default "${wasm.toString("base64")}";\n`,
  );
  writeFileSync(join(generatedDir, "SOURCE_HASH"), `${sourceHash()}\n`);
  console.log(`wasm: ${wasm.length} bytes`);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
